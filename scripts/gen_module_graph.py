#!/usr/bin/env python3
"""Generate the VEN's module import graph into docs/architecture/module_dependency_graph.md.

The hand-drawn component diagram in that file says what each part does; this section says which
top-level module imports which, read from the code, so it cannot drift (R-35). One node per
top-level `VEN/src` module (`controller/milp_planner/` is its own: the ring map puts it in infra),
one edge per `crate::<module>` / `lab_core::` reference in production code. Production code means
what `audit_ven_architecture.code_lines` keeps: comments and `#[cfg(test)]` blocks stripped.

  python scripts/gen_module_graph.py          rewrite the generated section
  python scripts/gen_module_graph.py --check  exit 1 if it is stale (audit_module_graph.py runs this)
"""
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from audit_ven_architecture import REPO_ROOT, VEN_SRC, code_lines, rust_files  # noqa: E402

DOC = REPO_ROOT / "docs" / "architecture" / "module_dependency_graph.md"
BEGIN = "<!-- BEGIN GENERATED by scripts/gen_module_graph.py -->"
END = "<!-- END GENERATED -->"

MILP = "controller/milp_planner"
LAB_CORE = "lab-core"

# The ring map of `.claude/CLAUDE.md` (ven-architecture), outer to inner. A module not listed is
# wiring or support code (boot, state, profile, ...) and is drawn in its own group.
RINGS = [
    ("Adapters", ["routes", "tasks"]),
    ("Application", ["services"]),
    ("Domain", ["entities", "controller"]),
    ("Infra", ["assets", "simulator", "vtn", MILP, LAB_CORE]),
]
OTHER = "Wiring & support"

CRATE_PATH = re.compile(r"\bcrate::(\w+)(?:::(\w+))?")
LAB_CORE_PATH = re.compile(r"\blab_core::")


def module_of(rel: str) -> str:
    """Top-level module of a path relative to `VEN/src`."""
    parts = rel.replace("\\", "/").split("/")
    if parts[:2] == ["controller", "milp_planner"]:
        return MILP
    return parts[0][:-3] if len(parts) == 1 and parts[0].endswith(".rs") else parts[0]


def edges(lines_by_file: "dict[str, list[str]]", modules=None) -> "set[tuple[str, str]]":
    """`(from, to)` for every module a file's production lines name, self-references dropped.

    `modules`, when given, is what a `crate::<name>` target must be; anything else is an item
    re-exported at the crate root (`crate::AppCtx`), not a module. `scan` always passes it.
    """
    out = set()
    for rel, lines in lines_by_file.items():
        src = module_of(rel)
        for line in lines:
            for top, sub in CRATE_PATH.findall(line):
                dst = MILP if (top, sub) == ("controller", "milp_planner") else top
                if dst != src and (modules is None or dst in modules):
                    out.add((src, dst))
            if LAB_CORE_PATH.search(line):
                out.add((src, LAB_CORE))
    return out


def node_id(module: str) -> str:
    return "M_" + re.sub(r"\W", "_", module)


def node_label(module: str) -> str:
    if module == LAB_CORE:
        return "lab-core (crate)"
    return module + ("/" if (VEN_SRC / module).is_dir() else ".rs")


def render(modules, edge_set) -> str:
    """The generated Mermaid block: one subgraph per ring, everything sorted."""
    mods = sorted(set(modules) | {m for e in edge_set for m in e})
    ringed = {m for _, ms in RINGS for m in ms}
    groups = [(name, [m for m in ms if m in mods]) for name, ms in RINGS]
    groups.append((OTHER, [m for m in mods if m not in ringed]))
    out = ["```mermaid", "graph LR"]
    for i, (name, ms) in enumerate(groups):
        if not ms:
            continue
        out.append(f'  subgraph G{i}["{name}"]')
        out += [f'    {node_id(m)}["{node_label(m)}"]' for m in ms]
        out.append("  end")
    out += [f"  {node_id(a)} --> {node_id(b)}" for a, b in sorted(edge_set)]
    out.append("```")
    return "\n".join(out) + "\n"


def replace_section(doc: str, block: str) -> str:
    start, end = doc.find(BEGIN), doc.find(END)
    if start < 0 or end < start:
        raise ValueError(f"{DOC.name} has no {BEGIN} ... {END} section")
    return doc[: start + len(BEGIN)] + "\n" + block + doc[end:]


def scan() -> str:
    lines_by_file = {
        str(f.relative_to(VEN_SRC)): [line for _, line in code_lines(f)] for f in rust_files(VEN_SRC)
    }
    modules = {module_of(rel) for rel in lines_by_file}
    return render(modules, edges(lines_by_file, modules))


def main(argv) -> int:
    doc = DOC.read_text(encoding="utf-8")
    fresh = replace_section(doc, scan())
    if "--check" in argv:
        if fresh != doc:
            print(f"FAIL  {DOC.relative_to(REPO_ROOT)}: generated module graph is stale; "
                  "run python scripts/gen_module_graph.py")
            return 1
        print("OK    generated module graph is current")
        return 0
    DOC.write_text(fresh, encoding="utf-8", newline="\n")
    print(f"wrote {DOC.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
